hl.on("hyprland.start", function()
    -- waybar via rice-mode so it starts with the stylesheet matching the
    -- stored mode (style.css vs style-pro.css). See bin/rice-mode.
    hl.exec_cmd("rice-mode waybar-start")
    -- awww-daemon-start, not bare awww-daemon: at login the wayland socket
    -- often isn't accepting clients yet, and awww 0.12.1 panics+coredumps
    -- instead of waiting. The wrapper retries until the daemon connects.
    hl.exec_cmd("awww-daemon-start")
    hl.exec_cmd("mako")
    hl.exec_cmd("systemctl --user start hyprpolkitagent")
    -- rice-mode apply: paints the wallpaper for the stored mode (shuffle in
    -- rice mode, the pinned static image in pro mode) and matches blur/opacity.
    hl.exec_cmd("rice-mode apply")
    -- Sleep a bit — hopefully everything was initialized. Then loop wallpapers.
    hl.exec_cmd("sleep 5; hyprwallpapers_loop 300")
    -- eww widgets: ghosted desktop calendar (control center is toggled from waybar)
    hl.exec_cmd("eww daemon && eww open calendar-ghost")
    hl.dispatch(hl.dsp.focus({ workspace = 1 }))
end)


