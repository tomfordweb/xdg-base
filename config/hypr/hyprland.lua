-- Blur the bar, launcher and notifications (glass look).
-- ignore_alpha is a THRESHOLD, not a boolean: pixels with alpha below it are
-- left unblurred. 0 blurs everything — including the fully transparent padding
-- of the layer surface, which is what painted that ugly frosted rectangle
-- around mako notifications. Keep it above the surface's own transparent
-- regions but below the real translucent panel background.
hl.layer_rule({
    name  = "glass-waybar",
    match = { namespace = "waybar" },

    blur         = true,
    ignore_alpha = 0.2,
})

hl.layer_rule({
    name  = "glass-wofi",
    match = { namespace = "wofi" },

    blur         = true,
    ignore_alpha = 0.5,
})

hl.layer_rule({
    name  = "glass-notifications",
    match = { namespace = "notifications" },

    blur         = true,
    ignore_alpha = 0.6,
})
