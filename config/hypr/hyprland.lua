-- Bambu Studio — let the main window TILE, but float + center only its
-- dialogs/popups so they never land off-screen. Bambu's blocking dialogs
-- (login, setup wizard, confirmations, errors) are X11 modal windows; the main
-- window never is — so match modal cleanly selects just the popups. Class is
-- BambuStudio for both the nix + AppImage builds.
hl.window_rule({
    name  = "bambu-dialog-center",
    match = { class = "^(BambuStudio)$", modal = true },

    float  = true,
    center = true,
})

-- wofi launches with --normal-window (see menu above) so clicking outside
-- moves focus and wofi's close_on_focus_loss can close it.
hl.window_rule({
    name  = "wofi-launcher",
    match = { class = "^(wofi)$" },

    float  = true,
    center = true,
})

hl.window_rule({
